// Stylesheets for GTK applications.
//
// GTK windows cannot be blurred by the compositor, so application surfaces
// always use the solid fallback colours. What carries over from the design
// is the palette, the accent, the radius scale and the window controls.

import {resolveTokens, hex} from '../tokens.js';
import {tokenOptions} from './index.js';

const MARKER = '/* Generated by Ubuntu Glass. Do not edit: it is rewritten whenever a setting changes. */';

function palette(t) {
    const {raw} = t;
    return {
        accent: hex(raw.accent),
        onAccent: hex(raw.onAccent),
        window: hex(raw.winSolid),
        view: hex(raw.elevSolid),
        sidebar: hex(raw.side),
        popover: hex(raw.elevSolid),
        text: hex(raw.text),
        red: hex(raw.red),
        green: hex(raw.green),
        amber: hex(raw.amber),
    };
}

// libadwaita 1.6+ reads CSS variables and can switch them with the system
// style while an application is running. Older GTK ignores this block.
function liveVariables(values, env) {
    const block = mode => {
        const p = palette(resolveTokens(tokenOptions(values, {...env, mode})));
        return `@media (prefers-color-scheme: ${mode}) {
  :root {
    --accent-bg-color: ${p.accent};
    --accent-fg-color: ${p.onAccent};
    --accent-color: ${p.accent};
    --window-bg-color: ${p.window};
    --window-fg-color: ${p.text};
    --view-bg-color: ${p.view};
    --view-fg-color: ${p.text};
    --headerbar-bg-color: ${p.window};
    --headerbar-fg-color: ${p.text};
    --headerbar-backdrop-color: ${p.window};
    --sidebar-bg-color: ${p.sidebar};
    --sidebar-fg-color: ${p.text};
    --sidebar-backdrop-color: ${p.sidebar};
    --popover-bg-color: ${p.popover};
    --popover-fg-color: ${p.text};
    --dialog-bg-color: ${p.popover};
    --dialog-fg-color: ${p.text};
    --destructive-bg-color: ${p.red};
    --success-color: ${p.green};
    --warning-color: ${p.amber};
  }
}`;
    };
    return `${block('dark')}\n\n${block('light')}`;
}

/**
 * Stylesheet for GTK 4 and libadwaita applications.
 *
 * @param {object} values - settings from the model
 * @param {object} env - see tokenOptions
 * @returns {string} CSS
 */
export function buildGtk4Css(values, env) {
    const t = resolveTokens(tokenOptions(values, env));
    const p = palette(t);
    const {r} = t;

    return `${MARKER}

@define-color accent_bg_color ${p.accent};
@define-color accent_fg_color ${p.onAccent};
@define-color accent_color ${p.accent};
@define-color window_bg_color ${p.window};
@define-color window_fg_color ${p.text};
@define-color view_bg_color ${p.view};
@define-color view_fg_color ${p.text};
@define-color headerbar_bg_color ${p.window};
@define-color headerbar_fg_color ${p.text};
@define-color headerbar_backdrop_color ${p.window};
@define-color sidebar_bg_color ${p.sidebar};
@define-color sidebar_fg_color ${p.text};
@define-color sidebar_backdrop_color ${p.sidebar};
@define-color popover_bg_color ${p.popover};
@define-color popover_fg_color ${p.text};
@define-color dialog_bg_color ${p.popover};
@define-color dialog_fg_color ${p.text};
@define-color destructive_bg_color ${p.red};
@define-color success_color ${p.green};
@define-color warning_color ${p.amber};

window.csd:not(.maximized):not(.fullscreen):not(.tiled),
window.csd:not(.maximized):not(.fullscreen):not(.tiled) > decoration {
  border-radius: ${r.md}px;
}

button:not(.circular):not(.pill),
entry,
spinbutton,
dropdown > button,
combobox > button {
  border-radius: ${r.sm}px;
}

.card,
list.boxed-list,
list.content {
  border-radius: ${r.md}px;
}

popover > contents {
  border-radius: ${r.md}px;
}

popover.menu modelbutton,
popover.menu .model button {
  border-radius: ${r.sm}px;
}

/* Window controls: round, on the right, with an accent close button. */
windowcontrols > button > image {
  border-radius: 999px;
}

windowcontrols > button.close:not(:backdrop) > image {
  background-color: @accent_bg_color;
  color: @accent_fg_color;
}

*:focus-visible {
  outline-color: alpha(@accent_bg_color, 0.9);
}

${liveVariables(values, env)}
`;
}

/**
 * Stylesheet for GTK 3 applications. Deliberately small: GTK 3 themes are
 * image-heavy, so only the parts that can be changed safely are touched.
 *
 * @param {object} values - settings from the model
 * @param {object} env - see tokenOptions
 * @returns {string} CSS
 */
export function buildGtk3Css(values, env) {
    const t = resolveTokens(tokenOptions(values, env));
    const p = palette(t);
    const {r} = t;

    return `${MARKER}

@define-color theme_selected_bg_color ${p.accent};
@define-color theme_selected_fg_color ${p.onAccent};
@define-color accent_bg_color ${p.accent};
@define-color accent_fg_color ${p.onAccent};

decoration,
window.csd,
.titlebar:not(.maximized) {
  border-radius: ${r.md}px ${r.md}px 0 0;
}

button:not(.circular),
entry {
  border-radius: ${r.sm}px;
}

headerbar button.titlebutton.close:not(:backdrop),
.titlebar button.titlebutton.close:not(:backdrop) {
  background-color: @accent_bg_color;
  color: @accent_fg_color;
}
`;
}
