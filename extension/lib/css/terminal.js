// Terminal palette and opacity for Ptyxis, Ubuntu's terminal.
//
// The mockup's terminal is graphite glass in dark mode and warm paper in
// light mode, with the theme's semantic colours for prompt and output. Ptyxis
// palettes carry both variants in one file and switch with the system style.

import {resolveTokens, hex} from '../tokens.js';
import {tokenOptions} from './index.js';

export const PALETTE_ID = 'Ubuntu-Glass';

// ANSI colours 0-15 for each appearance. 1-6 are the design's red, green,
// amber, blue, aubergine and a matching teal; 9-14 are lighter (dark mode)
// or deeper (light mode) versions of the same hues.
const ANSI = {
    dark: [
        '#1E1F24', '#EC6A62', '#5BC287', '#E9B84E', '#7AA7E0', '#C77AA4', '#5FB8B5', '#D5D4D0',
        '#6E6F76', '#F28C85', '#80D3A3', '#F2CB74', '#9DC0EC', '#D99BBE', '#86CFCC', '#F2F1EE',
    ],
    light: [
        '#2A2A2D', '#C63C34', '#2C8A52', '#9A6A10', '#2F6DB5', '#8E3A6A', '#1E7A78', '#D9D8D5',
        '#6E6E73', '#A9302A', '#226E41', '#7E560C', '#245894', '#732E56', '#17615F', '#F4F3F0',
    ],
};

// Terminal surfaces from the design: rgba(18,19,22,0.9) and rgba(252,251,249,0.94).
const SURFACE = {
    dark: {background: '#121316', alpha: 0.90},
    light: {background: '#FCFBF9', alpha: 0.94},
};

function variant(values, env, mode) {
    const t = resolveTokens(tokenOptions(values, {...env, mode}));
    const lines = [
        `Background=${SURFACE[mode].background}`,
        `Foreground=${hex(t.raw.text)}`,
        `Cursor=${hex(t.raw.accent)}`,
        ...ANSI[mode].map((c, i) => `Color${i}=${c}`),
    ];
    return `[${mode === 'dark' ? 'Dark' : 'Light'}]\n${lines.join('\n')}\n`;
}

/**
 * The Ptyxis palette file.
 *
 * @param {object} values - settings from the model
 * @param {object} env - see tokenOptions; `mode` is ignored, both are written
 * @returns {string} palette file contents
 */
export function buildTerminalPalette(values, env) {
    return `# Generated by Ubuntu Glass. Do not edit: it is rewritten whenever a setting changes.
[Palette]
Name=Ubuntu Glass

${variant(values, env, 'light')}
${variant(values, env, 'dark')}`;
}

/**
 * Window opacity for the terminal profile. Ptyxis has one opacity per
 * profile, so it follows the appearance currently in use.
 *
 * @param {object} values - settings from the model
 * @param {object} env - see tokenOptions
 * @returns {number} opacity between 0 and 1
 */
export function terminalOpacity(values, env) {
    const {opts} = resolveTokens(tokenOptions(values, env));
    if (!opts.glass)
        return 1;
    const designed = SURFACE[env.mode === 'light' ? 'light' : 'dark'].alpha;
    let alpha = 1 - (1 - designed) * Math.min(100, Math.max(0, opts.intensity)) / 100;
    if (!opts.transparency)
        alpha = Math.max(alpha, 0.96);
    if (opts.highContrast)
        alpha = Math.max(alpha, 0.96);
    return Math.round(alpha * 100) / 100;
}
