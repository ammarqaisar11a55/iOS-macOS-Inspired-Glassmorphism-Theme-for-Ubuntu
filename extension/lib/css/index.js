// Assembles the shell stylesheet from the per-component builders.
//
// Each component is included only when its switch is on, so turning one off
// removes exactly that component's rules and nothing else.

import {resolveTokens} from '../tokens.js';
import {panelCss} from './panel.js';
import {dockCss} from './dock.js';
import {quickSettingsCss} from './quickSettings.js';
import {notificationsCss} from './notifications.js';
import {menusCss} from './menus.js';
import {dialogsCss} from './dialogs.js';
import {overviewCss} from './overview.js';

/**
 * Translate stored settings into token options.
 *
 * @param {object} values - settings from the model
 * @param {object} env
 * @param {string} env.mode - 'dark' or 'light', already resolved
 * @param {string|null} [env.systemAccent] - GNOME accent as #RRGGBB
 * @param {boolean} [env.systemAnimations] - GNOME's enable-animations
 * @returns {object} options for resolveTokens
 */
export function tokenOptions(values, {mode, systemAccent = null, systemAnimations = true}) {
    return {
        mode,
        accent: values['accent'],
        systemAccent,
        glass: values['glass-effects'],
        transparency: values['transparency'],
        intensity: values['glass-intensity'],
        borders: values['glass-borders'],
        shadows: values['shadows'],
        rounded: values['rounded-corners'],
        reducedMotion: values['reduced-motion'] || !systemAnimations,
        highContrast: values['high-contrast'],
    };
}

/**
 * Build the complete shell stylesheet.
 *
 * @param {object} values - settings from the model
 * @param {object} env - see tokenOptions
 * @returns {string} CSS; empty when every component is switched off
 */
export function buildShellCss(values, env) {
    const t = resolveTokens(tokenOptions(values, env));
    const parts = [];

    // Menus go first: quick settings and the date menu refine the generic
    // popup rules and rely on coming later in the sheet.
    if (values['menus-style'])
        parts.push(menusCss(t));
    if (values['panel-style'])
        parts.push(panelCss(t));
    if (values['dock-style']) {
        parts.push(dockCss(t, {
            animations: values['dock-animations'] && !t.opts.reducedMotion,
        }));
    }
    if (values['quick-settings-style'])
        parts.push(quickSettingsCss(t));
    if (values['notifications-style'])
        parts.push(notificationsCss(t));
    if (values['dialogs-style'])
        parts.push(dialogsCss(t));
    if (values['overview-style'])
        parts.push(overviewCss(t));

    if (!parts.length)
        return '';
    return `/* Generated by Ubuntu Glass (${t.mode}). Do not edit: it is rewritten whenever a setting changes. */\n\n${parts.join('\n')}`;
}
